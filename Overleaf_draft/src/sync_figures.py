"""
Sync Figures to Overleaf_draft/version_Professor/figures/

Syncs ONLY whitelisted figures that are referenced in .tex files:
1. Evaluation figures: outputs/evaluation/ → version_Professor/figures/evaluation/
2. Training figures: Overleaf_draft/figures/training/ → version_Professor/figures/training/

Usage:
    python Overleaf_draft/src/sync_figures.py          # Dry run - shows what would be copied
    python Overleaf_draft/src/sync_figures.py --sync   # Actually copy files

Output:
    [NEW]    - File doesn't exist in destination
    [UPDATE] - Source file is newer than destination (based on mtime)
    [SAME]   - Source file is same age or older than destination
    [SKIP]   - Directory not found or no whitelisted files
    [WARNING]- Expected file not found in source

To add/remove files: Edit the USED_FILES and TRAINING_FILES dicts below.
"""

import shutil
import sys
from pathlib import Path

# Paths
SCRIPT_DIR = Path(__file__).parent
PROJECT_ROOT = SCRIPT_DIR.parent.parent
OUTPUTS_EVAL = PROJECT_ROOT / "outputs" / "evaluation"

# Destination: version_Professor (the active paper directory)
VERSION_PROFESSOR = SCRIPT_DIR.parent / "version_Professor"
OVERLEAF_FIGURES = VERSION_PROFESSOR / "figures" / "evaluation"
OVERLEAF_APPENDIX = VERSION_PROFESSOR / "figures" / "appendix"
OVERLEAF_TRAINING = VERSION_PROFESSOR / "figures" / "training"

# Source for training figures (generated by generate_training_plots.py)
SRC_TRAINING = SCRIPT_DIR.parent / "figures" / "training"

# =============================================================================
# WHITELIST: Only these files are used in .tex (from grep "includegraphics")
# =============================================================================

# Training figures (from Overleaf_draft/figures/training/)
# These are the 3 training plots actively used in version_Professor .tex files
TRAINING_FILES = [
    'combined_eval_loss',      # 11_appendix.tex:508 - 1x3 (no SFT)
    'combined_accuracy',       # 11_appendix.tex:680 - DPO/CITA only (no SFT)
    'dpo_cita_margins',        # 11_appendix.tex:688, 6_experiments.tex:110
    # Note: sft_loss and sft_mean_token_accuracy are COMMENTED OUT in .tex
]

# Evaluation figures (from outputs/evaluation/)
USED_FILES = {
    'AQI_Evaluation': [
        'aqi_comparison',
    ],
    'Conditional_Safety_Evaluation': [
        'conditional_safety_comparison',
    ],
    'ISD_Evaluation_Embedding': [
        'isd_comparison',
    ],
    'Length_Control_Evaluation': [
        'length_control_comparison',
    ],
    'TruthfulQA_Evaluation': [
        'truthfulqa_comparison',
    ],
    'combined_plots': [
        'heatmap',
        'heatmap_no_ci',
        'radar_area',
        # teaser_single_prompt_idx287 moved to figures/misc/ (manually created)
    ],
    'appendix': [
        'hp_ablation_combined',
        'hp_pareto_frontier',
        'hp_ablation_beta',
        'hp_ablation_lambda_kl',
        'hp_ablation_learning_rate',
    ],
}

# Source directories
SOURCE_DIRS = {
    'AQI_Evaluation': OUTPUTS_EVAL / 'AQI_Evaluation',
    'Conditional_Safety_Evaluation': OUTPUTS_EVAL / 'Conditional_Safety_Evaluation',
    'ISD_Evaluation_Embedding': OUTPUTS_EVAL / 'ISD_Evaluation_Embedding',
    'Length_Control_Evaluation': OUTPUTS_EVAL / 'Length_Control_Evaluation',
    'TruthfulQA_Evaluation': OUTPUTS_EVAL / 'TruthfulQA_Evaluation',
    'combined_plots': OUTPUTS_EVAL / 'combined_plots',
    'appendix': OUTPUTS_EVAL / 'combined_plots' / 'appendix',
}

# File extensions to sync
FIGURE_EXTENSIONS = ['.pdf', '.png']


def get_whitelisted_files(src_dir: Path, whitelist: list) -> list:
    """Get only whitelisted figure files from a source directory."""
    files = []
    if src_dir.exists():
        for basename in whitelist:
            for ext in FIGURE_EXTENSIONS:
                filepath = src_dir / f"{basename}{ext}"
                if filepath.exists():
                    files.append(filepath)
    return files


def sync_file(src_file: Path, dest_file: Path, files_to_copy: list) -> str:
    """Check file status and add to copy list. Returns status string."""
    files_to_copy.append((src_file, dest_file))
    if dest_file.exists():
        src_mtime = src_file.stat().st_mtime
        dest_mtime = dest_file.stat().st_mtime
        return "[UPDATE]" if src_mtime > dest_mtime else "[SAME]"
    return "[NEW]"


def main():
    dry_run = '--sync' not in sys.argv

    print("=" * 70)
    print("SYNC FIGURES TO version_Professor (Whitelisted Only)")
    print("=" * 70)
    print(f"Destination: {VERSION_PROFESSOR}/figures/")
    print(f"Mode: {'DRY RUN (use --sync to actually copy)' if dry_run else 'SYNC MODE'}")
    print()

    # Ensure destination directories exist
    OVERLEAF_FIGURES.mkdir(parents=True, exist_ok=True)
    (OVERLEAF_FIGURES / 'combined_plots').mkdir(parents=True, exist_ok=True)
    OVERLEAF_APPENDIX.mkdir(parents=True, exist_ok=True)
    OVERLEAF_TRAINING.mkdir(parents=True, exist_ok=True)

    files_to_copy = []
    missing_files = []

    # =========================================================================
    # PART 1: TRAINING FIGURES (from Overleaf_draft/figures/training/)
    # =========================================================================
    print("=" * 70)
    print("TRAINING FIGURES")
    print("=" * 70)
    print(f"Source: {SRC_TRAINING}")
    print(f"Dest:   {OVERLEAF_TRAINING}")
    print(f"Whitelisted: {len(TRAINING_FILES)} basenames")

    if SRC_TRAINING.exists():
        for basename in TRAINING_FILES:
            for ext in FIGURE_EXTENSIONS:
                src_file = SRC_TRAINING / f"{basename}{ext}"
                if src_file.exists():
                    dest_file = OVERLEAF_TRAINING / src_file.name
                    status = sync_file(src_file, dest_file, files_to_copy)
                    print(f"  {status} {src_file.name}")
                else:
                    missing_files.append(f"training/{basename}{ext}")
    else:
        print(f"  [SKIP] Source directory not found")

    # =========================================================================
    # PART 2: EVALUATION FIGURES (from outputs/evaluation/)
    # =========================================================================
    print("\n" + "=" * 70)
    print("EVALUATION FIGURES")
    print("=" * 70)
    print(f"Source: {OUTPUTS_EVAL}")

    for name, src_dir in SOURCE_DIRS.items():
        print(f"\n[{name}]")

        if not src_dir.exists():
            print(f"  [SKIP] Source directory not found: {src_dir}")
            continue

        # Determine destination
        if name == 'combined_plots':
            dest_dir = OVERLEAF_FIGURES / 'combined_plots'
        elif name == 'appendix':
            dest_dir = OVERLEAF_APPENDIX
        else:
            dest_dir = OVERLEAF_FIGURES

        # Get whitelisted files
        whitelist = USED_FILES.get(name, [])
        src_files = get_whitelisted_files(src_dir, whitelist)

        # Check for missing files
        for basename in whitelist:
            for ext in FIGURE_EXTENSIONS:
                expected = src_dir / f"{basename}{ext}"
                if not expected.exists():
                    missing_files.append(str(expected.relative_to(PROJECT_ROOT)))

        if not src_files:
            print(f"  [SKIP] No whitelisted files found")
            continue

        for src_file in src_files:
            dest_file = dest_dir / src_file.name
            status = sync_file(src_file, dest_file, files_to_copy)
            print(f"  {status} {src_file.name}")

    # Summary
    print("\n" + "=" * 70)
    print("SUMMARY")
    print("=" * 70)
    print(f"Files to sync: {len(files_to_copy)}")

    if missing_files:
        print(f"\n[WARNING] {len(missing_files)} expected files not found:")
        for mf in missing_files[:10]:  # Show first 10
            print(f"  - {mf}")
        if len(missing_files) > 10:
            print(f"  ... and {len(missing_files) - 10} more")

    if not files_to_copy:
        print("\nNo files to sync!")
        return

    # Copy files
    if dry_run:
        print("\n[DRY RUN] No files copied. Run with --sync to actually copy.")
    else:
        print("\nCopying files...")
        copied_count = 0
        figures_root = OVERLEAF_FIGURES.parent  # figures/ directory
        for src_file, dest_file in files_to_copy:
            try:
                shutil.copy2(src_file, dest_file)
                rel_path = dest_file.relative_to(figures_root)
                print(f"  [COPIED] {src_file.name} -> {rel_path}")
                copied_count += 1
            except Exception as e:
                print(f"  [ERROR] {src_file.name}: {e}")
        print(f"\nCopied {copied_count}/{len(files_to_copy)} files")


if __name__ == "__main__":
    main()
